// ScrapeUnblocker's public "YouTube Channel Scraper" Actor: https://apify.com/scrapeunblocker/youtube-channel-scraper
const ACTOR_ID = '25G45hB2Gmu9OBx0t';
const INTEGRATION_APP_ID = 'scrapeunblocker-youtube-channel-scraper';

// Node option name -> Actor input key.
const OPTION_FIELDS: Record<string, OptionField> = {
	proxyCountry: {
		key: 'proxy_country',
		kind: 'upper',
	},
};

function buildActorInput(
	this: IExecuteFunctions,
	resource: string,
	operation: string,
	options: IDataObject,
	itemIndex: number,
): IDataObject {
	const input: IDataObject = {};

	switch (`${resource}:${operation}`) {
		case 'video:getAll': {
			input.channel = requireString.call(this, 'channel', 'Channel', itemIndex);
			input.limit = this.getNodeParameter('limit', itemIndex);
			break;
		}
		default:
			throw new NodeOperationError(
				this.getNode(),
				`The operation "${operation}" is not supported for resource "${resource}"`,
				{ itemIndex },
			);
	}

	applyOptions(input, options, OPTION_FIELDS);
	return input;
}

